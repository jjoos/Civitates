// Vite content-hashes the JS bundle, but files in public/ keep stable URLs and
// GitHub Pages serves them with max-age=600. So a data-only change ships a
// fresh bundle that then reads a STALE cached JSON — which is exactly how a
// fixed dataset kept rendering as the old one.
//
// Fix: hash each data file at build time and bake the hashes into the bundle,
// so the app requests data/foo.json?v=<hash>. Per-file, so changing the small
// historic dataset does not force a re-download of the 9 MB BAG file.
import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';

const DATA = new URL('../public/data/', import.meta.url);
const OUT = new URL('../src/data-manifest.ts', import.meta.url);

const entries = [];
for (const file of (await readdir(DATA)).sort()) {
  const buf = await readFile(new URL(file, DATA));
  entries.push([file, createHash('sha256').update(buf).digest('hex').slice(0, 10)]);
}

await writeFile(OUT,
  '// GENERATED by scripts/gen-data-manifest.mjs — do not edit.\n'
  + 'export const DATA_VERSION: Record<string, string> = '
  + `${JSON.stringify(Object.fromEntries(entries), null, 2)};\n\n`
  + '/** Cache-busted URL for a file in public/data. */\n'
  + 'export function dataUrl(base: string, file: string): string {\n'
  + '  const v = DATA_VERSION[file];\n'
  + '  return `${base}data/${file}${v ? `?v=${v}` : \'\'}`;\n'
  + '}\n');
console.log(`data manifest: ${entries.map(([f, h]) => `${f}=${h}`).join(', ')}`);
